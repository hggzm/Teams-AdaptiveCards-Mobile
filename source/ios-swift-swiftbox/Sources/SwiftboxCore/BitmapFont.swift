public extension Framebuffer {
    /// Draw `text` with its top-left at `(x, y)` in `color`, clipping to bounds.
    /// Returns the x just past the last glyph (the next draw position).
    @discardableResult
    func drawText(_ text: String, x: Int, y: Int, color: Color) -> Int {
        var penX = x
        for character in text {
            if let columns = BitmapFont.columns(for: character) {
                for (c, byte) in columns.enumerated() {
                    for r in 0..<BitmapFont.glyphHeight where (byte >> UInt8(r)) & 1 == 1 {
                        setPixel(x: penX + c, y: y + r, to: color)
                    }
                }
            }
            penX += BitmapFont.advance
        }
        return penX
    }
}
