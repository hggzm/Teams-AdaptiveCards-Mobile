import Foundation

/// A compact 5×7 bitmap font for software text rendering into a ``Framebuffer``
/// — labels for the swiftbox desktop's window titles and panel (ROADMAP
/// Phase 6.2). Pure data + `Foundation`, so it renders identically on every
/// platform including the iOS sandbox.
///
/// Each glyph is five column bytes; in each byte bit `r` (0…6, 0 = top) lit means
/// a pixel at that row. Glyphs cover printable ASCII `0x20`–`0x60`; lowercase
/// letters fold onto the uppercase shapes (a legible, conventional choice for a
/// minimal bitmap UI), and anything else renders blank. Columns are the classic
/// 5×7 dot-matrix patterns.
public enum BitmapFont {
    public static let glyphWidth = 5
    public static let glyphHeight = 7
    /// Pixels advanced per character (glyph + one column of spacing).
    public static let advance = 6

    /// Column bytes for a character, folding lowercase to uppercase; `nil` (→
    /// blank) for anything outside the supported set.
    public static func columns(for character: Character) -> [UInt8]? {
        if let g = glyphs[character] { return g }
        if let scalar = character.unicodeScalars.first,
           scalar.value >= 0x61, scalar.value <= 0x7A,
           let upper = Unicode.Scalar(scalar.value - 0x20) {
            return glyphs[Character(upper)]
        }
        return nil
    }

    /// Width in pixels of `text` rendered at this font's advance.
    public static func width(of text: String) -> Int {
        text.isEmpty ? 0 : text.count * advance - 1
    }

